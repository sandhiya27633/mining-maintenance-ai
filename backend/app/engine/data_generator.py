"""
data_generator.py — Synthetic Dataset Generator
================================================
Duty-Cycle-Based Predictive Maintenance System for Heavy Mining Vehicles

IMPORTANT: ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC.
It is generated from statistical distributions designed to approximate realistic
mining vehicle operating conditions. It does NOT represent real sensor readings,
real vehicle behaviour, or real maintenance outcomes. It must NOT be used to make
claims about real-world system performance.

Generates:
  - data/raw/vehicles_meta.csv   : static vehicle metadata (one row per vehicle)
  - data/raw/operational_data_raw.csv : daily operational records (one row per vehicle per day)

Includes realistic correlations:
  - Higher load + route severity -> higher engine hours (compounding wear)
  - Higher fault count -> higher fault severity (fault clustering)
  - Operating stress index correlated with load + route severity
  - Recent service reduces immediate fault probability
  - Vehicle age increases base fault probability

Injects realistic data quality issues as specified in config.py:
  - Missing load values (MISSING_LOAD)
  - Invalid load values > 100 or < 0 (INVALID_LOAD)
  - Missing engine hours (MISSING_ENGINE_HOURS)
  - Duplicate records (DUPLICATE_RECORD)
  - Invalid mileage (cumulative decreases) (INVALID_MILEAGE)
  - Missing fault information (MISSING_FAULT_INFO)

Usage:
  python src/data_generator.py

Expected output:
  data/raw/vehicles_meta.csv         (40 rows)
  data/raw/operational_data_raw.csv  (~14,600 rows + injected duplicates)
  Console summary statistics
"""

