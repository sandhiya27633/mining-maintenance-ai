# ---------------------------------------------------------------------------
# Helper utilities
# ---------------------------------------------------------------------------

def _clip(value: float, low: float, high: float) -> float:
    """Clip a scalar value to [low, high]."""
    return max(low, min(high, value))


def _route_label(score: float) -> str:
    """Convert a 0–10 route severity score to a display label."""
    for label, (lo, hi) in cfg.ROUTE_SEVERITY_LABELS.items():
        if lo <= score <= hi:
            return label
    # Fallback: score == 10.0 exactly
    return "Extreme"


def _sigmoid(x: float) -> float:
    """Numerically stable sigmoid."""
    if x >= 0:
        return 1.0 / (1.0 + np.exp(-x))
    exp_x = np.exp(x)
    return exp_x / (1.0 + exp_x)


